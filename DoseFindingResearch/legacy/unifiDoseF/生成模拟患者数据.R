# 独立运行本文件即可生成模拟试验患者的毒性数据，无需加载额外 R 包。
# 输出：bank[患者编号, 剂量编号, 试验编号]，毒性等级为 0、1、2、3。
# 每名患者在各剂量下的毒性分别抽样，表示预生成的潜在结局；
# 实际模拟试验时，再按分配的剂量读取相应数据。

# 1. 设置真实毒性分布：行对应毒性等级 0:3，列对应剂量 1:6。
ptox <- rbind(
  c(0.83, 0.75, 0.62, 0.51, 0.34, 0.19),
  c(0.12, 0.15, 0.18, 0.19, 0.16, 0.11),
  c(0.04, 0.07, 0.11, 0.14, 0.15, 0.11),
  c(0.01, 0.03, 0.09, 0.16, 0.35, 0.59)
)



# 3. 设置模拟参数。
ntrial <- 2000      # 独立模拟试验次数
nmax <- 30          # 每次试验最多患者数
ndose <- ncol(ptox) # 剂量水平数

set.seed(2026)      # 保证结果可重复

# 4. 创建三维数组：患者 × 剂量 × 试验。
bank <- array(
  NA_integer_,
  dim = c(nmax, ndose, ntrial)
)

# 5. 生成所有模拟试验的患者数据。
for (d in seq_len(ndose)) {
   # 对第 d 个剂量，一次性抽 60000 个毒性等级（0~3）
  
